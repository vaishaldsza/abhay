# Sensitive timing/rescue trigger keywords when status has no driver accepted
PRE_ACCEPTANCE_TRIGGER_KEYWORDS = [
    # English
    "dispatched", "en route", "on the way", "heading to", "arriving", "rescue", "rescuer",
    "sending a vehicle", "sent a vehicle", "ambulance", "boat", "coming soon",
    "minutes away", "mins away", "safe now",
    # Hindi
    "आ रही", "रास्ते में", "भेज दिया", "बचाव", "सुरक्षित",
    # Kannada
    "ಬರುತ್ತಿದೆ", "ದಾರಿಯಲ್ಲಿದೆ", "ಕಳುಹಿಸಲಾಗಿದೆ", "ಸುರಕ್ಷಿತ"
]

def is_safe_acknowledgment(text: str, request_status: str = "request_recorded") -> Tuple[bool, str]:
    """
    Evaluates whether an LLM-generated string violates safety rules.
    Returns (is_safe, reason).
    """
    if not text:
        return True, "empty"

    lowered = text.lower().strip()

    # 1. Check against blocked phrases (regardless of status)
    for phrase in BLOCKED_PHRASES:
        if phrase.lower() in lowered:
            return False, f"Blocked forbidden promise phrase: '{phrase}'"

    # 2. If driver has not accepted, block ANY rescue/timing/dispatch words
    accepted_statuses = {"driver_accepted", "on_run", "picked_up", "evacuated"}
    if request_status not in accepted_statuses:
        for kw in PRE_ACCEPTANCE_TRIGGER_KEYWORDS:
            pattern = rf"\b{re.escape(kw.lower())}\b"
            if re.search(pattern, lowered) or kw.lower() in lowered:
                return False, f"Pre-acceptance violation: contains forbidden trigger '{kw}'"

    return True, "safe"

def sanitize_llm_reply(llm_reply: str, request_status: str, fallback_template: str) -> str:
    """
    If the LLM text passes safety verification, returns it; otherwise drops it and returns the fallback template.
    """
    safe, reason = is_safe_acknowledgment(llm_reply, request_status)
    if not safe:
        # Drop the LLM text completely and return strictly the approved template
        return fallback_template
    return llm_reply
